import math
# python build in math function 
# min, max
print("MIN:", min(5, 3, 10, 11))
print("MAX:", max(5, 3, 10, 11))
print("ABS (positive number):", abs(-123))
print("POWER (pangkat):", pow(5,3))
# akar quadrat
print("SEQUARE ROOT OF NUMBER:", math.sqrt(16)) # 4 because 4x4 = 16
# dibulatkan keatas
print("CEIL:", math.ceil(1.4))
# dibulatkan kebawah
print("FLOOR", math.floor(1.4))

